const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const path = require('node:path');
const vscode = require('vscode');
exports.run = async function (root) {
  const fixture = path.join(root, 'borrowed-tasks');
  await fs.mkdir(fixture, {recursive:true});
  await fs.copyFile(path.join(__dirname, '../../../playground/manifest.json'), path.join(fixture, 'manifest.json'));
  const source = await fs.readFile(path.join(__dirname, '../../../playground/borrowed_tasks.tellur'), 'utf8');
  const uri = vscode.Uri.file(path.join(fixture, 'main.tellur'));
  await fs.writeFile(uri.fsPath, source);
  const document = await vscode.workspace.openTextDocument(uri);
  await vscode.window.showTextDocument(document);
  await vscode.extensions.getExtension('tellur-language-local.tellur-language').activate();
  const diagnostics = () => vscode.languages.getDiagnostics(uri).filter(d => d.source === 'tellur');
  const code = d => typeof d.code === 'object' ? d.code.value : d.code;
  async function waitFor(predicate, description) {
    const until = Date.now() + 15000;
    while (Date.now() < until) {
      if (await predicate()) return;
      await new Promise(resolve => setTimeout(resolve, 50));
    }
    throw new Error(`Timed out: ${description}; ${JSON.stringify(diagnostics())}`);
  }
  async function replace(text) {
    const edit = new vscode.WorkspaceEdit();
    edit.replace(uri, new vscode.Range(document.positionAt(0), document.positionAt(document.getText().length)), text);
    assert.ok(await vscode.workspace.applyEdit(edit));
  }
  async function hover(needle) {
    const at = document.getText().lastIndexOf(needle);
    assert.ok(at >= 0);
    const hovers = await vscode.commands.executeCommand('vscode.executeHoverProvider', uri, document.positionAt(at));
    return (hovers ?? []).flatMap(h => h.contents.map(c => String(c.value))).join('\n');
  }
  await waitFor(async () => diagnostics().length === 0 && (await hover('auto pending')).includes('task<display>'), 'pending task type hover');
  assert.ok((await hover('defer display')).includes('storage stays borrowed'));
  assert.ok((await hover('await pending')).includes('consumes a local cold task'));
  const broken = source.replace('emit("before await");', 'text = "too soon";');
  assert.notEqual(broken, source);
  await replace(broken);
  await waitFor(() => diagnostics().some(d => code(d) === 'E_LOAN'), 'pending loan conflict');
  assert.ok(!(await hover('auto pending')).includes('task<display>'));
  await replace(source);
  await waitFor(async () => diagnostics().length === 0 && (await hover('auto pending')).includes('task<display>'), 'repaired ownership');
  await document.save();
  const result = await vscode.commands.executeCommand('tellur.buildAndRun', {
    arguments:['--json'], output:path.join(root, 'native output', 'borrowed-tasks')
  });
  assert.equal(result.code, 0, result.stderr);
  const report = JSON.parse(result.stdout);
  assert.equal(report.outcome, 'done');
  assert.deepEqual(report.events.filter(e => e.kind === 'emit').map(e => e.message), ['before await', 'initial', 'updated']);
  await fs.writeFile(path.join(fixture, 'passed.txt'), 'pending type hover, loan diagnostic, unsaved repair and native execution passed\n');
  console.log('TELLUR_BORROWED_TASKS_EDITOR_TESTS_PASSED: pending type hover, diagnostic repair and native run');
};
